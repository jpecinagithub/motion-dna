const dicts: Record<Lang, Dict> = { es, en };

export function useLang(): Lang {
  return useAppStore((s) => s.lang);
}

/** Translation hook: const { t } = useT(); t('timeline.play') */
export function useT(): { t: (key: DictKey) => string; lang: Lang } {
  const lang = useLang();
  return {
    lang,
    t: (key: DictKey) => dicts[lang][key] ?? dicts.en[key] ?? key,
  };
}

export function translate(lang: Lang, key: DictKey): string {
  return dicts[lang][key] ?? dicts.en[key] ?? key;
}
